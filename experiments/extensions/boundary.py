#!/usr/bin/env python3
"""Changed-assumption boundary and triviality checks for the selected contract.

The labelled theorem: on the sigma-algebra generated by doubly-principal
labelled cylinders, a finite countably additive complex measure with the
prescribed CTP amplitudes exists iff p in [0,1].

The conditional covariant extension (research/creative/COVARIANT_RESULT.md):
on the covariant post algebra, with nu(P_infinity)=1 and a common finite
factor kappa for EVERY principal post past H,
  nu(D_H) = kappa N(H) A_p(H),
a finite complex measure exists iff 0 < p <= 1.

This script checks the boundary around that extension. It is not a proof of
the conditional theorem and does not construct a rank-dependent measure.
Standard library only.
"""
import sys
import math
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "baseline"))
import poscau  # noqa: E402


def V(n, p):
    """Sum of |A_p(C)| over doubly-principal naturally labelled n-causets."""
    total = 0.0
    for rel in poscau.causets(n):
        if not poscau.is_principal(rel, n):
            continue
        parent = frozenset((i, j) for (i, j) in rel if j < n - 1)
        if not poscau.is_principal(parent, n - 1):
            continue
        total += abs(poscau.amplitude(rel, n, p))
    return total


def rank_dependent_bound():
    p = 0.5 + 0.5j
    t = abs(p) + abs(1 - p)     # > 1 off [0,1]
    s = abs(1 - p) / t
    c_s = math.prod(1 - s ** j for j in range(1, 200))
    print(f"Rank-dependent factor boundary at p={p}: t={t:.6f}, s={s:.6f}, c_s={c_s:.6f}")
    print("  Required: |kappa_n| V_n <= ||nu||_TV for every n (disjoint rank events).")
    print("  Sufficient lower bound: V_n >= |p| t^(n-2) c_s.")
    print("  n | V_n (computed) | 1/V_n (||nu||=1) | lower-bound 1/kappa_n")
    for n in (5, 6):
        v = V(n, p)
        lb = abs(p) * t ** (n - 2) * c_s
        print(f"  {n} | {v:.6f} | {1/v:.6f} | {1/lb:.6f}")
    print("  A constant kappa is excluded because V_n -> infinity (t>1).")
    print("  An exponentially decaying kappa_n is not excluded by this necessary bound.")
    print("  No rank-dependent extension is constructed here; the classification is open.")
    print()


def shape_dependent_vacuity():
    print("Shape-dependent factor triviality:")
    print("  For any finite measure nu and any principal H with N(H) A_p(H) != 0,")
    print("  set kappa_H := nu(D_H)/(N(H) A_p(H)); the rule")
    print("  nu(D_H) = kappa_H N(H) A_p(H) then holds by definition.")
    print("  A shape-dependent 'factorization' therefore has no predictive content;")
    print("  only a shape-blind (common or rank-only) rule can constrain p.")
    print()


def endpoint_reduction():
    print("Known-result reduction at the endpoints:")
    print("  p=0: the labelled theorem gives the infinite-antichain probability measure;")
    print("       it has no posts, so nu(P_infinity)=0 and the conditional theorem's")
    print("       normalization premise fails. Hence the 0<p<=1 scope, not [0,1].")
    print("  p=1: the infinite chain; every element is a post, nu(P_infinity)=1,")
    print("       kappa = c(0) = 1; the conditional theorem includes p=1.")
    print("  For 0<p<1: classical CTP restricted to the covariant algebra gives")
    print("       kappa = c(1-p) = prod_j (1-(1-p)^j) > 0.")
    print()


def normalization_and_zero():
    print("Normalization / zero-measure checks:")
    print("  Without nu(P_infinity)=1, kappa=0 gives the zero measure for every p;")
    print("  normalization is what turns kappa=0 into a contradiction.")
    print("  The all-principal requirement is essential: the Dirac history in")
    print("  countermodel.py satisfies the doubly-principal-only rule with kappa=0")
    print("  and nu(P_infinity)=1 for every p, but violates the all-principal rule.")
    print()


def vector_valued_boundary():
    print("Vector-valued measures (search bound, no construction):")
    print("  The proof uses finite total variation of a scalar complex measure.")
    print("  A countably additive Banach-valued measure need not have finite total")
    print("  variation (e.g. sum e_n/n converges in l^2 but is not absolutely summable),")
    print("  so the divergence argument does not transfer verbatim. No Hilbert-valued")
    print("  extension or counterexample was constructed; this is an open scope boundary,")
    print("  not a claim that one exists.")
    print()


def main():
    rank_dependent_bound()
    shape_dependent_vacuity()
    endpoint_reduction()
    normalization_and_zero()
    vector_valued_boundary()
    print("No unbounded claim here rests on finite search: the divergence V_n -> infinity")
    print("is the analytic two-cap bound, and the finite values above only illustrate it.")


if __name__ == "__main__":
    main()
